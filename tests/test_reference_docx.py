def test_shipped_reference_structure():
    assert SHIPPED.exists(), "the CV phase requires %s to ship with the skill" % SHIPPED.relative_to(ROOT)
    _assert_structure(mk.inspect(SHIPPED), "shipped reference.docx")


def test_regenerated_reference_structure():
    """The regeneration path must work with the pandoc that is actually installed.

    pandoc <= 3.1 ships a self-closing <w:sectPr />; later versions ship a
    populated one. The script used to handle only the second, leaving pgMar
    outside sectPr -- silently ignored, one-inch margins, three pages.
    """
    _need("pandoc")
    with tempfile.TemporaryDirectory() as tmp:
        out = pathlib.Path(tmp) / "reference.docx"
        assert mk.main(["--out", str(out)]) == 0
        _assert_structure(mk.inspect(out), "regenerated reference.docx")


def test_sect_pr_rewrite_handles_every_shape():
    """Pure-string check of the sectPr rewrite, independent of pandoc's version."""
    body = '<w:body><w:p/>%s</w:body>'
    shapes = {
        "self-closing": '<w:sectPr />',
        "self-closing, no space": '<w:sectPr/>',
        "empty pair": '<w:sectPr></w:sectPr>',
        "populated": '<w:sectPr><w:footnotePr><w:numRestart w:val="eachSect"/></w:footnotePr></w:sectPr>',
        "populated, stale pgMar": '<w:sectPr><w:pgMar w:top="1440"/><w:footnotePr/></w:sectPr>',
        "type + docGrid": '<w:sectPr><w:type w:val="continuous"/><w:docGrid w:linePitch="360"/></w:sectPr>',
        "absent": '',
    }
    for label, sect in shapes.items():
        out = mk.force_sect_pr(body % sect, "a4")
        m = re.search(r"<w:sectPr\b[^>]*>(.*?)</w:sectPr>", out, re.S)
        assert m, "%s: no sectPr pair in output" % label
        inner = m.group(1)
        assert inner.count("<w:pgMar") == 1 and out.count("<w:pgMar") == 1, "%s: pgMar not exactly once inside sectPr" % label
        assert inner.count("<w:pgSz") == 1, "%s: pgSz not exactly once inside sectPr" % label
        assert 'w:top="720"' in inner, "%s: stale margin survived" % label
        assert inner.index("<w:pgSz") < inner.index("<w:pgMar"), "%s: pgSz must precede pgMar" % label
        if "<w:type" in inner:
            assert inner.index("<w:type") < inner.index("<w:pgSz") < inner.index("<w:docGrid"), \
                "%s: schema order type < pgSz/pgMar < docGrid broken" % label


def test_style_rewrite_never_duplicates_sizes():
    """force_rpr / force_doc_defaults replace sizes, never stack a second w:sz."""
    with_size = '<w:style w:styleId="X"><w:name w:val="X"/><w:rPr><w:sz w:val="24" /><w:szCs w:val="24" /></w:rPr></w:style>'
    bare = '<w:style w:styleId="X"><w:name w:val="X"/><w:qFormat/></w:style>'
    for block in (with_size, bare):
        out = mk.force_spacing(mk.force_rpr(block, 20), 0, 60)
        assert re.findall(r'<w:sz w:val="(\d+)"', out) == ["20"], out
        assert out.count("<w:pPr>") == 1 and out.count("<w:spacing") == 1, out
        assert out.index("<w:pPr>") < out.index("<w:rPr>"), "pPr must precede rPr: %s" % out
    defaults = '<w:docDefaults><w:rPrDefault><w:rPr><w:sz w:val="24" /><w:szCs w:val="24" /></w:rPr></w:rPrDefault></w:docDefaults>'
    out = mk.force_doc_defaults(defaults, 20)
    assert re.findall(r'<w:sz w:val="(\d+)"', out) == ["20"], out


def test_colour_is_stripped_from_every_style():
    """Harvard style is black and white; pandoc's default is not."""
    styles = (
        '<w:styles><w:style w:styleId="Heading1"><w:rPr>'
        '<w:color w:val="0F4761"/><w:b/></w:rPr></w:style>'
        '<w:style w:styleId="Hyperlink"><w:rPr>'
        '<w:color w:val="4F81BD" w:themeColor="hyperlink"/><w:u w:val="single"/>'
        '</w:rPr></w:style></w:styles>'
    )
    out = mk.strip_colour(styles)
    assert "<w:color" not in out, out
    assert "<w:b/>" in out and '<w:u w:val="single"/>' in out, \
        "weights and underlines must survive: %s" % out


def test_defaults_are_created_when_pandoc_ships_none():
    """pin_font/force_doc_defaults must survive a styles.xml without the
    containers they write into -- the very drift this script exists to absorb.
    The old pin_font did m.group(0) on a None match and crashed."""
    shapes = {
        "no docDefaults": '<w:styles xmlns:w="x"><w:style w:styleId="Normal"/></w:styles>',
        "empty docDefaults": '<w:styles xmlns:w="x"><w:docDefaults></w:docDefaults></w:styles>',
        "self-closing docDefaults": '<w:styles xmlns:w="x"><w:docDefaults/></w:styles>',
        "rPrDefault without rPr": '<w:styles xmlns:w="x"><w:docDefaults><w:rPrDefault></w:rPrDefault></w:docDefaults></w:styles>',
        "self-closing rPrDefault": '<w:styles xmlns:w="x"><w:docDefaults><w:rPrDefault/></w:docDefaults></w:styles>',
        "self-closing rPr": '<w:styles xmlns:w="x"><w:docDefaults><w:rPrDefault><w:rPr/></w:rPrDefault></w:docDefaults></w:styles>',
    }
    for label, xml in shapes.items():
        out = mk.pin_font(mk.force_doc_defaults(xml, 20), "Calibri")
        block = re.search(r"<w:rPrDefault\b[^>]*>.*?</w:rPrDefault>", out, re.S)
        assert block, "%s: no rPrDefault in output" % label
        assert re.findall(r'<w:sz w:val="(\d+)"', block.group(0)) == ["20"], "%s: size not set once: %s" % (label, out)
        assert re.findall(r'<w:rFonts [^>]*w:ascii="([^"]+)"', block.group(0)) == ["Calibri"], "%s: font not pinned once: %s" % (label, out)
        assert out.count("<w:docDefaults") == 1 and out.count("<w:rPrDefault") == 1, "%s: containers duplicated: %s" % (label, out)
    try:
        mk.pin_font("<not-styles/>", "Calibri")
    except mk.TemplateError:
        pass
    else:
        raise AssertionError("pin_font returned unchanged XML instead of raising on a document with no <w:styles> root")


def test_bold_overrides_an_explicit_off_and_keeps_schema_order():
    """<w:b w:val="0"/> means 'not bold' and used to survive the rewrite; and
    inserted run properties must follow rStyle/rFonts, not precede them."""
    off = '<w:style w:styleId="H"><w:name w:val="H"/><w:rPr><w:rFonts w:ascii="X"/><w:b w:val="0"/><w:bCs w:val="0"/><w:sz w:val="24"/></w:rPr></w:style>'
    out = mk.force_bold(mk.force_rpr(off, 20))
    inner = re.search(r"<w:rPr>(.*?)</w:rPr>", out, re.S).group(1)
    assert 'w:val="0"' not in inner, out
    assert inner.count("<w:b/>") == 1 and inner.count("<w:bCs/>") == 1, out
    assert re.findall(r'<w:sz w:val="(\d+)"', inner) == ["20"], out
    order = [m.group(1) for m in re.finditer(r"<w:(rFonts|b|bCs|sz|szCs)\b", inner)]
    assert order == ["rFonts", "b", "bCs", "sz", "szCs"], "rPr children out of schema order: %s" % order


def test_inspect_fails_closed_when_a_heading_style_is_missing():
    """A renamed or dropped heading style used to report zero problems -- the
    gate failed open in exactly the mode it was added for."""
    with tempfile.TemporaryDirectory() as tmp:
        broken = pathlib.Path(tmp) / "reference.docx"
        with zipfile.ZipFile(SHIPPED) as zin, zipfile.ZipFile(broken, "w", zipfile.ZIP_DEFLATED) as zout:
            for item in zin.infolist():
                data = zin.read(item.filename)
                if item.filename == "word/styles.xml":
                    text = data.decode("utf-8")
                    text = re.sub(r'<w:style [^>]*w:styleId="Heading2".*?</w:style>', "", text, count=1, flags=re.S)
                    assert 'w:styleId="Heading2"' not in text
                    data = text.encode("utf-8")
                zout.writestr(item, data)
        report = mk.inspect(broken)
        assert "Heading2" in report["missing_styles"], report
        assert any("Heading2" in p for p in report["problems"]), "inspect() reported no problem for a missing heading style: %r" % report["problems"]


