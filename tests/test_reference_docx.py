def _need(*tools: str) -> None:
    missing = [t for t in tools if shutil.which(t) is None]
    if not missing:
        return
    msg = "missing tools: %s (apt: pandoc libreoffice-writer poppler-utils)" % ", ".join(missing)
    if os.environ.get("CI"):
        raise AssertionError(msg)
    raise unittest.SkipTest(msg)


def _assert_structure(report: dict, label: str) -> None:
    assert not report["problems"], "%s is not usable:\n  - %s" % (label, "\n  - ".join(report["problems"]))
    assert report["pgSz"] in ({"w": w, "h": h} for w, h in mk.PAGE_SIZES.values()), \
        "%s: pgSz %r is not one of the known page sizes" % (label, report["pgSz"])
    assert report["coloured_styles"] == [], \
        "%s: Harvard style is black and white, but these styles carry a colour: %s" % (label, report["coloured_styles"])


def _render(md: pathlib.Path, workdir: pathlib.Path, reference: pathlib.Path | None) -> dict:
    """markdown -> docx -> pdf, exactly as the skill instructs; return what the gate reads."""
    docx = workdir / ("with-ref.docx" if reference else "stock.docx")
    cmd = ["pandoc", str(md), "-o", str(docx)]
    if reference:
        cmd += ["--reference-doc=%s" % reference]
    subprocess.run(cmd, check=True)

    # A private profile dir keeps LibreOffice from tripping over a running
    # instance or a locked default profile (the usual reason it hangs in CI).
    profile = workdir / "lo-profile"
    subprocess.run(
        ["libreoffice", "--headless", "-env:UserInstallation=file://%s" % profile,
         "--convert-to", "pdf", str(docx), "--outdir", str(workdir)],
        check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=180,
    )
    pdf = docx.with_suffix(".pdf")
    assert pdf.exists(), "LibreOffice produced no PDF for %s" % docx.name

    info = subprocess.run(["pdfinfo", str(pdf)], capture_output=True, text=True, check=True).stdout
    pages = int(re.search(r"^Pages:\s+(\d+)", info, re.M).group(1))
    text = subprocess.run(["pdftotext", str(pdf), "-"], capture_output=True, text=True, check=True).stdout
    bbox = subprocess.run(["pdftotext", "-bbox-layout", "-f", "1", "-l", "1", str(pdf), "-"],
                          capture_output=True, text=True, check=True).stdout
    xs = [float(x) for x in re.findall(r'<line xMin="([\d.]+)"', bbox)]
    return {"pages": pages, "text": text, "left_margin_pt": min(xs) if xs else None, "pdf": pdf}


def _chromatic_pixels(pdf: pathlib.Path, workdir: pathlib.Path, page: int = 1, threshold: int = 30) -> tuple[int, int]:
    """Rasterize one page and count pixels whose channels differ by more than
    ``threshold`` -- i.e. anything that is not black, white or grey.

    Uses pdftoppm's default PPM (P6) output, parsed by hand so the test needs no
    imaging library. Text anti-aliasing is greyscale, so a black-and-white page
    scores zero; pandoc's blue headings score in the thousands at 60 dpi.
    """
    stem = workdir / ("raster-%s" % pdf.stem)
    subprocess.run(["pdftoppm", "-r", "60", "-f", str(page), "-l", str(page), str(pdf), str(stem)],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    ppm = next(workdir.glob("raster-%s*.ppm" % pdf.stem))
    data = ppm.read_bytes()
    fields, i = [], 0
    while len(fields) < 4:  # magic, width, height, maxval
        while data[i:i + 1].isspace():
            i += 1
        j = i
        while not data[j:j + 1].isspace():
            j += 1
        fields.append(data[i:j])
        i = j
    i += 1
    assert fields[0] == b"P6", "expected a binary PPM, got %r" % fields[0]
    width, height = int(fields[1]), int(fields[2])
    px = data[i:i + width * height * 3]
    chromatic = 0
    for k in range(0, len(px), 3):
        r, g, b = px[k], px[k + 1], px[k + 2]
        if max(r, g, b) - min(r, g, b) > threshold:
            chromatic += 1
    return chromatic, width * height


