#!/usr/bin/env python3
"""Tests for the pandoc reference document that renders the master CV.

Two layers:

1. **Structure.** The shipped ``assets/reference.docx`` -- and a fresh one
   regenerated by ``scripts/make-reference-docx.py`` with whatever pandoc is
   installed -- must carry the metrics the CV phase relies on: half-inch
   margins *inside* ``sectPr``, a pinned page size, no coloured styles, a single
   10pt document default, and the per-style sizes. Needs only ``pandoc`` (for
   the regeneration case).

2. **Render.** The fixture CV in ``tests/fixtures/cv-fixture.md`` (~6,500
   characters, the size of a real two-page master) is pushed through the exact
   pipeline ``references/02-master-cv.md`` prescribes -- pandoc -> .docx ->
   LibreOffice -> .pdf -> pdfinfo/pdftotext -- and must land on two pages with
   its text intact, its margins measurably at half an inch and not one chromatic
   pixel on the page (Harvard style is black and white). As a control,
   the same CV without the reference document must NOT fit, which is the whole
   reason the asset exists. Needs ``pandoc``, ``libreoffice`` and poppler
   (``pdfinfo``, ``pdftotext``, ``pdftoppm``); skipped when they are missing
   unless ``CI`` is set, in which case missing tools fail the run.

Run:  python3 tests/test_reference_docx.py      (or: pytest tests/)
"""

from __future__ import annotations

import importlib.util
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile
import traceback
import unittest

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKILL = ROOT / "skills" / "fix-cv-find-job-skill"
SHIPPED = SKILL / "assets" / "reference.docx"
FIXTURE = ROOT / "tests" / "fixtures" / "cv-fixture.md"
SCRIPT = ROOT / "scripts" / "make-reference-docx.py"

_spec = importlib.util.spec_from_file_location("make_reference_docx", SCRIPT)
mk = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(mk)

MAX_PAGES = 2               # the gate in references/02-master-cv.md
MIN_TEXT_CHARS = 5000       # "a PDF that yields almost no characters is an image"
HALF_INCH_PT = 36.0
MUST_SURVIVE = (            # spot-check from the reference file: contact, employers, metrics
    "maria.fernandez@example.com",
    "+54 11 5555 0000",
    "Acme Logistics S.A.",
    "Supermercados Sol",
    "31%",
    "USD 210k/yr",
)


