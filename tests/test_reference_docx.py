def test_fixture_renders_on_two_pages_with_shipped_reference():
    _need("pandoc", "libreoffice", "pdfinfo", "pdftotext")
    with tempfile.TemporaryDirectory() as tmp:
        r = _render(FIXTURE, pathlib.Path(tmp), SHIPPED)
        assert r["pages"] <= MAX_PAGES, "fixture CV rendered on %d pages with the shipped reference (gate: <= %d)" % (r["pages"], MAX_PAGES)
        assert len(r["text"]) >= MIN_TEXT_CHARS, "PDF yields only %d characters -- is it an image?" % len(r["text"])
        for needle in MUST_SURVIVE:
            assert needle in r["text"], "%r did not survive into the PDF text" % needle
        assert r["left_margin_pt"] is not None and r["left_margin_pt"] < HALF_INCH_PT + 4, \
            "left margin measured at %.1fpt; expected ~%.0fpt (half an inch)" % (r["left_margin_pt"], HALF_INCH_PT)


def test_shipped_reference_renders_black_and_white():
    """Phase 2 promises the Harvard style: black and white. Measure it on the page."""
    _need("pandoc", "libreoffice", "pdfinfo", "pdftotext", "pdftoppm")
    with tempfile.TemporaryDirectory() as tmp:
        work = pathlib.Path(tmp)
        r = _render(FIXTURE, work, SHIPPED)
        chromatic, total = _chromatic_pixels(r["pdf"], work)
        assert chromatic == 0, \
            "page 1 has %d chromatic pixels of %d (%.2f%%): something on the page is not black, white or grey" % (
                chromatic, total, 100.0 * chromatic / total)


def test_shipped_reference_pins_the_font():
    """The rendered font must not depend on pandoc's theme of the day.

    pandoc 3.9's default theme is Aptos, which has no metric-compatible
    substitute on Linux and falls back to DejaVu Sans -- wide enough to push a
    full second page onto a third. The template pins Calibri, which LibreOffice
    renders as the metric-compatible Carlito, so the PDF must embed only that
    family, in a regular and a bold face (headings are bold now that colour is
    gone).
    """
    _need("pandoc", "libreoffice", "pdfinfo", "pdftotext", "pdffonts")
    _need_font("Carlito", "fonts-crosextra-carlito")
    with tempfile.TemporaryDirectory() as tmp:
        r = _render(FIXTURE, pathlib.Path(tmp), SHIPPED)
        out = subprocess.run(["pdffonts", str(r["pdf"])], capture_output=True, text=True, check=True).stdout
        faces = [line.split()[0].split("+")[-1] for line in out.splitlines()[2:] if line.strip()]
        # LibreOffice draws list bullets with OpenSymbol whatever the text font
        # is, and every real CV has bullets. It is a glyph font, not a text
        # font, so it cannot hide a leaked theme font: exclude it by name
        # rather than widening what the text faces are allowed to be.
        families = {f.split("-")[0] for f in faces} - {"OpenSymbol"}
        assert families and families <= {"Carlito", "Calibri"}, \
            "PDF embeds %s; expected only Calibri/Carlito -- a theme font leaked through" % sorted(families)
        assert any("Bold" in f for f in faces), "no bold face embedded: headings would not stand out (%s)" % faces


def test_stock_pandoc_styling_does_not_fit_control():
    """If this ever passes on two pages, the fixture is too short to prove anything."""
    _need("pandoc", "libreoffice", "pdfinfo", "pdftotext", "pdftoppm")
    with tempfile.TemporaryDirectory() as tmp:
        work = pathlib.Path(tmp)
        r = _render(FIXTURE, work, None)
        assert r["left_margin_pt"] is not None and r["left_margin_pt"] > 60, \
            "stock pandoc should render one-inch margins, measured %.1fpt" % r["left_margin_pt"]
        assert r["pages"] > MAX_PAGES, \
            "stock pandoc styling fit the fixture on %d pages: the fixture no longer exercises the reference document" % r["pages"]
        chromatic, _ = _chromatic_pixels(r["pdf"], work)
        assert chromatic > 0, \
            "stock pandoc should paint headings blue; if it no longer does, the black-and-white test proves nothing"


