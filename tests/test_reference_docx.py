def test_shipped_reference_pins_the_font():
    """The rendered font must not depend on pandoc's theme of the day.

    pandoc 3.9's default theme is Aptos, which has no metric-compatible
    substitute on Linux and falls back to DejaVu Sans -- wide enough to push a
    full second page onto a third. The template pins Calibri, which LibreOffice
    renders as the metric-compatible Carlito, so the PDF must embed only that
    family, in a regular and a bold face (headings are bold now that colour is
    gone).
    """
    _need("pandoc", "libreoffice", "pdfinfo", "pdftotext", "pdffonts")
    _need_font("Carlito", "fonts-crosextra-carlito")
    with tempfile.TemporaryDirectory() as tmp:
        r = _render(FIXTURE, pathlib.Path(tmp), SHIPPED)
        out = subprocess.run(["pdffonts", str(r["pdf"])], capture_output=True, text=True, check=True).stdout
        faces = [line.split()[0].split("+")[-1] for line in out.splitlines()[2:] if line.strip()]
        # LibreOffice draws list bullets with OpenSymbol whatever the text font
        # is, and every real CV has bullets. It is a glyph font, not a text
        # font, so it cannot hide a leaked theme font: exclude it by name
        # rather than widening what the text faces are allowed to be.
        families = {f.split("-")[0] for f in faces} - {"OpenSymbol"}
        assert families and families <= {"Carlito", "Calibri"}, \
            "PDF embeds %s; expected only Calibri/Carlito -- a theme font leaked through" % sorted(families)
        assert any("Bold" in f for f in faces), "no bold face embedded: headings would not stand out (%s)" % faces


